        P_POSTAL_CODE    IN STUDENT_ADDRESSES.POSTAL_CODE%TYPE,
        P_COUNTRY        IN STUDENT_ADDRESSES.COUNTRY%TYPE
    ) AS
    BEGIN
        UPDATE STUDENT_ADDRESSES
        SET ADDRESS_TYPE = UPPER(TRIM(P_ADDRESS_TYPE)),
            ADDRESS_LINE = P_ADDRESS_LINE,
            CITY = P_CITY,
            DISTRICT = P_DISTRICT,
            POSTAL_CODE = P_POSTAL_CODE,
            COUNTRY = NVL(P_COUNTRY, 'Bangladesh'),
            UPDATED_AT = SYSTIMESTAMP
        WHERE ADDRESS_ID = P_ADDRESS_ID;

        IF SQL%ROWCOUNT = 0 THEN
                RAISE_APPLICATION_ERROR(-20401, 'ADDRESS NOT FOUND.');
            END IF;

        EXCEPTION
            WHEN DUP_VAL_ON_INDEX THEN
                RAISE_APPLICATION_ERROR(
                    -20405,
                    'STUDENT ALREADY HAS THIS ADDRESS TYPE.'
                );

            WHEN OTHERS THEN
                RAISE_APPLICATION_ERROR(
                    -20406,
                    'ERROR UPDATING STUDENT ADDRESS: ' || SQLERRM
                );
    END UPDATE_ADDRESS;


    PROCEDURE DELETE_ADDRESS (
        P_ADDRESS_ID IN STUDENT_ADDRESSES.ADDRESS_ID%TYPE
    ) AS
    BEGIN
        DELETE FROM STUDENT_ADDRESSES
        WHERE ADDRESS_ID = P_ADDRESS_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20402, 'ADDRESS NOT FOUND.');
        END IF;
    END DELETE_ADDRESS;


