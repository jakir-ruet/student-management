        OPEN P_RESULT FOR
            SELECT
                TSA.TEACHER_SUBJECT_ASSIGNMENT_ID,
                TSA.CLASS_SUBJECT_ID,
                TSA.SECTION_SHIFT_ID,
                TSA.TEACHER_ID,
                S.SUBJECT_ID,
                S.SUBJECT_NAME,
                S.SUBJECT_CODE,
                TSA.ASSIGNMENT_TYPE,
                TSA.STATUS,
                TSA.CREATED_AT,
                TSA.UPDATED_AT
            FROM TEACHER_SUBJECT_ASSIGNMENTS TSA
            JOIN CLASS_SUBJECTS CS
              ON CS.CLASS_SUBJECT_ID =
                 TSA.CLASS_SUBJECT_ID
            JOIN SUBJECTS S
              ON S.SUBJECT_ID = CS.SUBJECT_ID
            ORDER BY
                TSA.TEACHER_ID,
                S.SUBJECT_NAME;

    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(
                -20824,
                'ERROR FETCHING TEACHER SUBJECT ASSIGNMENTS: '
                || SQLERRM
            );
    END GET_ALL_ASSIGNMENTS;


    PROCEDURE GET_ASSIGNMENTS_BY_TEACHER(
        P_TEACHER_ID IN  TEACHER_SUBJECT_ASSIGNMENTS.TEACHER_ID%TYPE,
        P_RESULT     OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                TSA.TEACHER_SUBJECT_ASSIGNMENT_ID,
                TSA.CLASS_SUBJECT_ID,
                TSA.SECTION_SHIFT_ID,
                TSA.TEACHER_ID,
                S.SUBJECT_ID,
                S.SUBJECT_NAME,
                S.SUBJECT_CODE,
                TSA.ASSIGNMENT_TYPE,
                TSA.STATUS,
                TSA.CREATED_AT,
                TSA.UPDATED_AT
            FROM TEACHER_SUBJECT_ASSIGNMENTS TSA
            JOIN CLASS_SUBJECTS CS
              ON CS.CLASS_SUBJECT_ID =
                 TSA.CLASS_SUBJECT_ID
            JOIN SUBJECTS S
              ON S.SUBJECT_ID = CS.SUBJECT_ID
            WHERE TSA.TEACHER_ID = P_TEACHER_ID
            ORDER BY S.SUBJECT_NAME;

    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(
                -20825,
                'ERROR FETCHING ASSIGNMENTS BY TEACHER: '
                || SQLERRM
            );
    END GET_ASSIGNMENTS_BY_TEACHER;


    PROCEDURE DELETE_ASSIGNMENT(
        P_ASSIGNMENT_ID IN TEACHER_SUBJECT_ASSIGNMENTS.TEACHER_SUBJECT_ASSIGNMENT_ID%TYPE
    ) AS
    BEGIN
        DELETE FROM TEACHER_SUBJECT_ASSIGNMENTS
        WHERE TEACHER_SUBJECT_ASSIGNMENT_ID =
              P_ASSIGNMENT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20302,
                'TEACHER SUBJECT ASSIGNMENT NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                -20826,
                'ERROR DELETING TEACHER SUBJECT ASSIGNMENT: '
                || SQLERRM
            );
    END DELETE_ASSIGNMENT;

