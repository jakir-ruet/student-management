--------------------------------------------------------
-- 1. SUBJECT_PKG - PACKAGE BODY
--------------------------------------------------------

CREATE OR REPLACE PACKAGE BODY SUBJECT_PKG AS

    PROCEDURE CREATE_SUBJECT(
        P_SUBJECT_NAME    IN  SUBJECTS.SUBJECT_NAME%TYPE,
        P_SUBJECT_CODE    IN  SUBJECTS.SUBJECT_CODE%TYPE,
        P_SUBJECT_TYPE    IN  SUBJECTS.SUBJECT_TYPE%TYPE,
        P_DESCRIPTION     IN  SUBJECTS.DESCRIPTION%TYPE,
        P_DISPLAY_ORDER   IN  SUBJECTS.DISPLAY_ORDER%TYPE,
        P_STATUS          IN  SUBJECTS.STATUS%TYPE,
        P_SUBJECT_ID      OUT SUBJECTS.SUBJECT_ID%TYPE
    ) AS
    BEGIN
        INSERT INTO SUBJECTS (
            SUBJECT_NAME,
            SUBJECT_CODE,
            SUBJECT_TYPE,
            DESCRIPTION,
            DISPLAY_ORDER,
            STATUS
        )
        VALUES (
            TRIM(P_SUBJECT_NAME),
            UPPER(TRIM(P_SUBJECT_CODE)),
            UPPER(TRIM(P_SUBJECT_TYPE)),
            P_DESCRIPTION,
            P_DISPLAY_ORDER,
            UPPER(TRIM(P_STATUS))
        )
        RETURNING SUBJECT_ID INTO P_SUBJECT_ID;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(
                -20101,
                'SUBJECT CODE ALREADY EXISTS'
            );

        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(
                -20801,
                'ERROR CREATING SUBJECT: ' || SQLERRM
            );
    END CREATE_SUBJECT;


    PROCEDURE UPDATE_SUBJECT(
        P_SUBJECT_ID      IN SUBJECTS.SUBJECT_ID%TYPE,
        P_SUBJECT_NAME    IN SUBJECTS.SUBJECT_NAME%TYPE,
        P_SUBJECT_CODE    IN SUBJECTS.SUBJECT_CODE%TYPE,
        P_SUBJECT_TYPE    IN SUBJECTS.SUBJECT_TYPE%TYPE,
        P_DESCRIPTION     IN SUBJECTS.DESCRIPTION%TYPE,
        P_DISPLAY_ORDER   IN SUBJECTS.DISPLAY_ORDER%TYPE,
        P_STATUS          IN SUBJECTS.STATUS%TYPE
    ) AS
    BEGIN
        UPDATE SUBJECTS
           SET SUBJECT_NAME  = TRIM(P_SUBJECT_NAME),
               SUBJECT_CODE  = UPPER(TRIM(P_SUBJECT_CODE)),
               SUBJECT_TYPE  = UPPER(TRIM(P_SUBJECT_TYPE)),
               DESCRIPTION   = P_DESCRIPTION,
               DISPLAY_ORDER = P_DISPLAY_ORDER,
               STATUS        = UPPER(TRIM(P_STATUS)),
               UPDATED_AT    = SYSTIMESTAMP
         WHERE SUBJECT_ID = P_SUBJECT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20102,
                'SUBJECT NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(
                -20101,
                'SUBJECT CODE ALREADY EXISTS'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                -20802,
                'ERROR UPDATING SUBJECT: ' || SQLERRM
            );
    END UPDATE_SUBJECT;


    PROCEDURE GET_SUBJECT_BY_ID(
        P_SUBJECT_ID IN  SUBJECTS.SUBJECT_ID%TYPE,
        P_RESULT     OUT SYS_REFCURSOR
    ) AS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM SUBJECTS
         WHERE SUBJECT_ID = P_SUBJECT_ID;

        IF V_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20102,
                'SUBJECT NOT FOUND'
            );
        END IF;

        OPEN P_RESULT FOR
            SELECT
                SUBJECT_ID,
                SUBJECT_NAME,
                SUBJECT_CODE,
                SUBJECT_TYPE,
                DESCRIPTION,
                DISPLAY_ORDER,
                STATUS,
                CREATED_AT,
                UPDATED_AT
            FROM SUBJECTS
            WHERE SUBJECT_ID = P_SUBJECT_ID;

    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                -20803,
                'ERROR FETCHING SUBJECT: ' || SQLERRM
            );
    END GET_SUBJECT_BY_ID;


    PROCEDURE GET_ALL_SUBJECTS(
        P_RESULT OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                SUBJECT_ID,
                SUBJECT_NAME,
                SUBJECT_CODE,
                SUBJECT_TYPE,
                DESCRIPTION,
                DISPLAY_ORDER,
                STATUS,
                CREATED_AT,
                UPDATED_AT
            FROM SUBJECTS
            ORDER BY
                NVL(DISPLAY_ORDER, 99999),
                SUBJECT_NAME;

    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(
                -20804,
                'ERROR FETCHING SUBJECTS: ' || SQLERRM
            );
    END GET_ALL_SUBJECTS;


    PROCEDURE DELETE_SUBJECT(
        P_SUBJECT_ID IN SUBJECTS.SUBJECT_ID%TYPE
    ) AS
    BEGIN
        DELETE FROM SUBJECTS
        WHERE SUBJECT_ID = P_SUBJECT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20102,
                'SUBJECT NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                -20805,
                'ERROR DELETING SUBJECT: ' || SQLERRM
            );
    END DELETE_SUBJECT;

END SUBJECT_PKG;
