CREATE INDEX IDX_ATT_SESSION_DATE
    ON ATTENDANCE_SESSIONS (ATTENDANCE_DATE);

CREATE INDEX IDX_ATT_SESSION_SECTION
    ON ATTENDANCE_SESSIONS (SECTION_SHIFT_ID);

CREATE INDEX IDX_ATT_SESSION_SUBJECT
    ON ATTENDANCE_SESSIONS (CLASS_SUBJECT_ID);

CREATE INDEX IDX_ATT_SESSION_TEACHER
    ON ATTENDANCE_SESSIONS (MARKED_BY_TEACHER_ID);

CREATE INDEX IDX_ATT_RECORD_SESSION
    ON ATTENDANCE_RECORDS (ATTENDANCE_SESSION_ID);

CREATE INDEX IDX_ATT_RECORD_ENROLLMENT
    ON ATTENDANCE_RECORDS (ENROLLMENT_ID);

CREATE INDEX IDX_ATT_RECORD_STATUS
    ON ATTENDANCE_RECORDS (ATTENDANCE_STATUS);