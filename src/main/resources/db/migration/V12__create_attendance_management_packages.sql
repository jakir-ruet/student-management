CREATE OR REPLACE PACKAGE BODY ATTENDANCE_RECORD_PKG AS

    PROCEDURE CREATE_RECORD(
        P_ATTENDANCE_SESSION_ID IN  ATTENDANCE_RECORDS.ATTENDANCE_SESSION_ID%TYPE,
        P_ENROLLMENT_ID         IN  ATTENDANCE_RECORDS.ENROLLMENT_ID%TYPE,
        P_ATTENDANCE_STATUS     IN  ATTENDANCE_RECORDS.ATTENDANCE_STATUS%TYPE,
        P_CHECK_IN_TIME         IN  ATTENDANCE_RECORDS.CHECK_IN_TIME%TYPE,
        P_REMARKS               IN  ATTENDANCE_RECORDS.REMARKS%TYPE,
        P_ATTENDANCE_RECORD_ID  OUT ATTENDANCE_RECORDS.ATTENDANCE_RECORD_ID%TYPE
    ) AS
        V_SESSION_SECTION_SHIFT_ID
            ATTENDANCE_SESSIONS.SECTION_SHIFT_ID%TYPE;

        V_ENROLL_SECTION_SHIFT_ID
            STUDENT_ENROLLMENTS.SECTION_SHIFT_ID%TYPE;

        V_SESSION_STATUS
            ATTENDANCE_SESSIONS.STATUS%TYPE;
    BEGIN
        SELECT SECTION_SHIFT_ID, STATUS
        INTO V_SESSION_SECTION_SHIFT_ID, V_SESSION_STATUS
        FROM ATTENDANCE_SESSIONS
        WHERE ATTENDANCE_SESSION_ID = P_ATTENDANCE_SESSION_ID;

        IF V_SESSION_STATUS IN ('LOCKED', 'CANCELLED') THEN
            RAISE_APPLICATION_ERROR(
                    -20603,
                    'ATTENDANCE RECORD CANNOT BE ADDED TO A LOCKED OR CANCELLED SESSION'
            );
        END IF;

        SELECT SECTION_SHIFT_ID
        INTO V_ENROLL_SECTION_SHIFT_ID
        FROM STUDENT_ENROLLMENTS
        WHERE ENROLLMENT_ID = P_ENROLLMENT_ID;

        IF V_SESSION_SECTION_SHIFT_ID <> V_ENROLL_SECTION_SHIFT_ID THEN
            RAISE_APPLICATION_ERROR(
                    -20604,
                    'STUDENT ENROLLMENT DOES NOT BELONG TO THE ATTENDANCE SESSION SECTION SHIFT'
            );
        END IF;

        INSERT INTO ATTENDANCE_RECORDS (
            ATTENDANCE_SESSION_ID,
            ENROLLMENT_ID,
            ATTENDANCE_STATUS,
            CHECK_IN_TIME,
            REMARKS
        )
        VALUES (
                   P_ATTENDANCE_SESSION_ID,
                   P_ENROLLMENT_ID,
                   UPPER(TRIM(NVL(P_ATTENDANCE_STATUS, 'PRESENT'))),
                   P_CHECK_IN_TIME,
                   P_REMARKS
               )
        RETURNING ATTENDANCE_RECORD_ID
        INTO P_ATTENDANCE_RECORD_ID;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                    -20605,
                    'ATTENDANCE SESSION OR STUDENT ENROLLMENT NOT FOUND'
            );

        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(
                    -20601,
                    'ATTENDANCE RECORD ALREADY EXISTS FOR THIS STUDENT AND SESSION'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20851,
                    'ERROR CREATING ATTENDANCE RECORD: ' || SQLERRM
            );
    END CREATE_RECORD;


    PROCEDURE UPDATE_RECORD(
        P_ATTENDANCE_RECORD_ID IN ATTENDANCE_RECORDS.ATTENDANCE_RECORD_ID%TYPE,
        P_ATTENDANCE_STATUS    IN ATTENDANCE_RECORDS.ATTENDANCE_STATUS%TYPE,
        P_CHECK_IN_TIME        IN ATTENDANCE_RECORDS.CHECK_IN_TIME%TYPE,
        P_REMARKS              IN ATTENDANCE_RECORDS.REMARKS%TYPE
    ) AS
        V_SESSION_STATUS ATTENDANCE_SESSIONS.STATUS%TYPE;
    BEGIN
        SELECT ATS.STATUS
        INTO V_SESSION_STATUS
        FROM ATTENDANCE_RECORDS AR
                 JOIN ATTENDANCE_SESSIONS ATS
                      ON ATS.ATTENDANCE_SESSION_ID = AR.ATTENDANCE_SESSION_ID
        WHERE AR.ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;

        IF V_SESSION_STATUS IN ('LOCKED', 'CANCELLED') THEN
            RAISE_APPLICATION_ERROR(
                    -20603,
                    'ATTENDANCE RECORD CANNOT BE UPDATED IN A LOCKED OR CANCELLED SESSION'
            );
        END IF;

        UPDATE ATTENDANCE_RECORDS
        SET ATTENDANCE_STATUS = UPPER(TRIM(P_ATTENDANCE_STATUS)),
            CHECK_IN_TIME     = P_CHECK_IN_TIME,
            REMARKS           = P_REMARKS,
            UPDATED_AT        = SYSTIMESTAMP
        WHERE ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                    -20602,
                    'ATTENDANCE RECORD NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                    -20602,
                    'ATTENDANCE RECORD NOT FOUND'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20852,
                    'ERROR UPDATING ATTENDANCE RECORD: ' || SQLERRM
            );
    END UPDATE_RECORD;


    PROCEDURE GET_RECORD_BY_ID(
        P_ATTENDANCE_RECORD_ID IN  ATTENDANCE_RECORDS.ATTENDANCE_RECORD_ID%TYPE,
        P_RESULT               OUT SYS_REFCURSOR
    ) AS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO V_COUNT
        FROM ATTENDANCE_RECORDS
        WHERE ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;

        IF V_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                    -20602,
                    'ATTENDANCE RECORD NOT FOUND'
            );
        END IF;

        OPEN P_RESULT FOR
            SELECT
                ATTENDANCE_RECORD_ID,
                ATTENDANCE_SESSION_ID,
                ENROLLMENT_ID,
                ATTENDANCE_STATUS,
                CHECK_IN_TIME,
                REMARKS,
                MARKED_AT,
                UPDATED_AT
            FROM ATTENDANCE_RECORDS
            WHERE ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;
    END GET_RECORD_BY_ID;


    PROCEDURE GET_RECORDS_BY_SESSION(
        P_ATTENDANCE_SESSION_ID IN  ATTENDANCE_RECORDS.ATTENDANCE_SESSION_ID%TYPE,
        P_RESULT                OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                AR.ATTENDANCE_RECORD_ID,
                AR.ATTENDANCE_SESSION_ID,
                AR.ENROLLMENT_ID,
                SE.STUDENT_ID,
                SE.ROLL_NUMBER,
                AR.ATTENDANCE_STATUS,
                AR.CHECK_IN_TIME,
                AR.REMARKS,
                AR.MARKED_AT,
                AR.UPDATED_AT
            FROM ATTENDANCE_RECORDS AR
                     JOIN STUDENT_ENROLLMENTS SE
                          ON SE.ENROLLMENT_ID = AR.ENROLLMENT_ID
            WHERE AR.ATTENDANCE_SESSION_ID =
                  P_ATTENDANCE_SESSION_ID
            ORDER BY SE.ROLL_NUMBER;
    END GET_RECORDS_BY_SESSION;


    PROCEDURE GET_RECORDS_BY_ENROLLMENT(
        P_ENROLLMENT_ID IN  ATTENDANCE_RECORDS.ENROLLMENT_ID%TYPE,
        P_RESULT        OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                AR.ATTENDANCE_RECORD_ID,
                AR.ATTENDANCE_SESSION_ID,
                AR.ENROLLMENT_ID,
                AR.ATTENDANCE_STATUS,
                AR.CHECK_IN_TIME,
                AR.REMARKS,
                AR.MARKED_AT,
                AR.UPDATED_AT
            FROM ATTENDANCE_RECORDS AR
            WHERE AR.ENROLLMENT_ID = P_ENROLLMENT_ID
            ORDER BY AR.MARKED_AT DESC;
    END GET_RECORDS_BY_ENROLLMENT;


    PROCEDURE DELETE_RECORD(
        P_ATTENDANCE_RECORD_ID IN ATTENDANCE_RECORDS.ATTENDANCE_RECORD_ID%TYPE
    ) AS
        V_SESSION_STATUS ATTENDANCE_SESSIONS.STATUS%TYPE;
    BEGIN
        SELECT ATS.STATUS
        INTO V_SESSION_STATUS
        FROM ATTENDANCE_RECORDS AR
                 JOIN ATTENDANCE_SESSIONS ATS
                      ON ATS.ATTENDANCE_SESSION_ID = AR.ATTENDANCE_SESSION_ID
        WHERE AR.ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;

        IF V_SESSION_STATUS = 'LOCKED' THEN
            RAISE_APPLICATION_ERROR(
                    -20603,
                    'ATTENDANCE RECORD CANNOT BE DELETED FROM A LOCKED SESSION'
            );
        END IF;

        DELETE FROM ATTENDANCE_RECORDS
        WHERE ATTENDANCE_RECORD_ID = P_ATTENDANCE_RECORD_ID;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                    -20602,
                    'ATTENDANCE RECORD NOT FOUND'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20853,
                    'ERROR DELETING ATTENDANCE RECORD: ' || SQLERRM
            );
    END DELETE_RECORD;

END ATTENDANCE_RECORD_PKG;
