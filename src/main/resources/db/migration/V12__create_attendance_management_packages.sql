CREATE OR REPLACE PACKAGE BODY STUDENT_ENROLLMENT_PKG AS

    PROCEDURE CREATE_ENROLLMENT(
        P_STUDENT_ID              IN  STUDENT_ENROLLMENTS.STUDENT_ID%TYPE,
        P_ACADEMIC_YEAR_CLASS_ID  IN  STUDENT_ENROLLMENTS.ACADEMIC_YEAR_CLASS_ID%TYPE,
        P_SECTION_SHIFT_ID        IN  STUDENT_ENROLLMENTS.SECTION_SHIFT_ID%TYPE,
        P_ROLL_NUMBER             IN  STUDENT_ENROLLMENTS.ROLL_NUMBER%TYPE,
        P_ENROLLMENT_DATE         IN  STUDENT_ENROLLMENTS.ENROLLMENT_DATE%TYPE,
        P_STATUS                  IN  STUDENT_ENROLLMENTS.STATUS%TYPE,
        P_REMARKS                 IN  STUDENT_ENROLLMENTS.REMARKS%TYPE,
        P_ENROLLMENT_ID           OUT STUDENT_ENROLLMENTS.ENROLLMENT_ID%TYPE
    ) AS
    BEGIN
        INSERT INTO STUDENT_ENROLLMENTS (
            STUDENT_ID,
            ACADEMIC_YEAR_CLASS_ID,
            SECTION_SHIFT_ID,
            ROLL_NUMBER,
            ENROLLMENT_DATE,
            STATUS,
            REMARKS
        )
        VALUES (
                   P_STUDENT_ID,
                   P_ACADEMIC_YEAR_CLASS_ID,
                   P_SECTION_SHIFT_ID,
                   NULLIF(TRIM(P_ROLL_NUMBER), ''),
                   NVL(P_ENROLLMENT_DATE, SYSDATE),
                   UPPER(TRIM(NVL(P_STATUS, 'ENROLLED'))),
                   P_REMARKS
               )
        RETURNING ENROLLMENT_ID
        INTO P_ENROLLMENT_ID;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(
                    -20401,
                    'STUDENT ENROLLMENT OR SECTION ROLL NUMBER ALREADY EXISTS'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20831,
                    'ERROR CREATING STUDENT ENROLLMENT: ' || SQLERRM
            );
    END CREATE_ENROLLMENT;


    PROCEDURE UPDATE_ENROLLMENT(
        P_ENROLLMENT_ID           IN STUDENT_ENROLLMENTS.ENROLLMENT_ID%TYPE,
        P_ACADEMIC_YEAR_CLASS_ID  IN STUDENT_ENROLLMENTS.ACADEMIC_YEAR_CLASS_ID%TYPE,
        P_SECTION_SHIFT_ID        IN STUDENT_ENROLLMENTS.SECTION_SHIFT_ID%TYPE,
        P_ROLL_NUMBER             IN STUDENT_ENROLLMENTS.ROLL_NUMBER%TYPE,
        P_ENROLLMENT_DATE         IN STUDENT_ENROLLMENTS.ENROLLMENT_DATE%TYPE,
        P_STATUS                  IN STUDENT_ENROLLMENTS.STATUS%TYPE,
        P_REMARKS                 IN STUDENT_ENROLLMENTS.REMARKS%TYPE
    ) AS
    BEGIN
        UPDATE STUDENT_ENROLLMENTS
        SET ACADEMIC_YEAR_CLASS_ID = P_ACADEMIC_YEAR_CLASS_ID,
            SECTION_SHIFT_ID       = P_SECTION_SHIFT_ID,
            ROLL_NUMBER            = NULLIF(TRIM(P_ROLL_NUMBER), ''),
            ENROLLMENT_DATE        = P_ENROLLMENT_DATE,
            STATUS                 = UPPER(TRIM(P_STATUS)),
            REMARKS                = P_REMARKS,
            UPDATED_AT             = SYSTIMESTAMP
        WHERE ENROLLMENT_ID = P_ENROLLMENT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                    -20402,
                    'STUDENT ENROLLMENT NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(
                    -20401,
                    'STUDENT ENROLLMENT OR SECTION ROLL NUMBER ALREADY EXISTS'
            );

        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20832,
                    'ERROR UPDATING STUDENT ENROLLMENT: ' || SQLERRM
            );
    END UPDATE_ENROLLMENT;


    PROCEDURE GET_ENROLLMENT_BY_ID(
        P_ENROLLMENT_ID IN  STUDENT_ENROLLMENTS.ENROLLMENT_ID%TYPE,
        P_RESULT        OUT SYS_REFCURSOR
    ) AS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO V_COUNT
        FROM STUDENT_ENROLLMENTS
        WHERE ENROLLMENT_ID = P_ENROLLMENT_ID;

        IF V_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                    -20402,
                    'STUDENT ENROLLMENT NOT FOUND'
            );
        END IF;

        OPEN P_RESULT FOR
            SELECT
                SE.ENROLLMENT_ID,
                SE.STUDENT_ID,
                SE.ACADEMIC_YEAR_CLASS_ID,
                SE.SECTION_SHIFT_ID,
                SE.ROLL_NUMBER,
                SE.ENROLLMENT_DATE,
                SE.STATUS,
                SE.REMARKS,
                SE.CREATED_AT,
                SE.UPDATED_AT
            FROM STUDENT_ENROLLMENTS SE
            WHERE SE.ENROLLMENT_ID = P_ENROLLMENT_ID;
    END GET_ENROLLMENT_BY_ID;


    PROCEDURE GET_ALL_ENROLLMENTS(
        P_RESULT OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                SE.ENROLLMENT_ID,
                SE.STUDENT_ID,
                SE.ACADEMIC_YEAR_CLASS_ID,
                SE.SECTION_SHIFT_ID,
                SE.ROLL_NUMBER,
                SE.ENROLLMENT_DATE,
                SE.STATUS,
                SE.REMARKS,
                SE.CREATED_AT,
                SE.UPDATED_AT
            FROM STUDENT_ENROLLMENTS SE
            ORDER BY
                SE.ACADEMIC_YEAR_CLASS_ID,
                SE.SECTION_SHIFT_ID,
                SE.ROLL_NUMBER;
    END GET_ALL_ENROLLMENTS;


    PROCEDURE GET_ENROLLMENTS_BY_STUDENT(
        P_STUDENT_ID IN  STUDENT_ENROLLMENTS.STUDENT_ID%TYPE,
        P_RESULT     OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                SE.ENROLLMENT_ID,
                SE.STUDENT_ID,
                SE.ACADEMIC_YEAR_CLASS_ID,
                SE.SECTION_SHIFT_ID,
                SE.ROLL_NUMBER,
                SE.ENROLLMENT_DATE,
                SE.STATUS,
                SE.REMARKS,
                SE.CREATED_AT,
                SE.UPDATED_AT
            FROM STUDENT_ENROLLMENTS SE
            WHERE SE.STUDENT_ID = P_STUDENT_ID
            ORDER BY SE.ENROLLMENT_DATE DESC;
    END GET_ENROLLMENTS_BY_STUDENT;


    PROCEDURE GET_ENROLLMENTS_BY_SECTION_SHIFT(
        P_SECTION_SHIFT_ID IN  STUDENT_ENROLLMENTS.SECTION_SHIFT_ID%TYPE,
        P_STATUS           IN  STUDENT_ENROLLMENTS.STATUS%TYPE,
        P_RESULT           OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN P_RESULT FOR
            SELECT
                SE.ENROLLMENT_ID,
                SE.STUDENT_ID,
                SE.ACADEMIC_YEAR_CLASS_ID,
                SE.SECTION_SHIFT_ID,
                SE.ROLL_NUMBER,
                SE.ENROLLMENT_DATE,
                SE.STATUS,
                SE.REMARKS,
                SE.CREATED_AT,
                SE.UPDATED_AT
            FROM STUDENT_ENROLLMENTS SE
            WHERE SE.SECTION_SHIFT_ID = P_SECTION_SHIFT_ID
              AND (
                P_STATUS IS NULL
                    OR SE.STATUS = UPPER(TRIM(P_STATUS))
                )
            ORDER BY SE.ROLL_NUMBER;
    END GET_ENROLLMENTS_BY_SECTION_SHIFT;


    PROCEDURE DELETE_ENROLLMENT(
        P_ENROLLMENT_ID IN STUDENT_ENROLLMENTS.ENROLLMENT_ID%TYPE
    ) AS
    BEGIN
        DELETE FROM STUDENT_ENROLLMENTS
        WHERE ENROLLMENT_ID = P_ENROLLMENT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                    -20402,
                    'STUDENT ENROLLMENT NOT FOUND'
            );
        END IF;

    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE BETWEEN -20999 AND -20000 THEN
                RAISE;
            END IF;

            RAISE_APPLICATION_ERROR(
                    -20833,
                    'ERROR DELETING STUDENT ENROLLMENT: ' || SQLERRM
            );
    END DELETE_ENROLLMENT;

END STUDENT_ENROLLMENT_PKG;
