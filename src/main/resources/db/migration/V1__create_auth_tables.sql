--------------------------------------------------------------
-- CREATE USERS TABLE
--------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USERNAME       VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(150) NOT NULL,
    PASSWORD_HASH  VARCHAR2(255) NOT NULL,
    FULL_NAME      VARCHAR2(150) NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    FAILED_LOGIN   NUMBER DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

--------------------------------------------------------------
-- CREATE LOGIN_HISTORY TABLE
--------------------------------------------------------------
CREATE TABLE LOGIN_HISTORY (
    LOGIN_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID       NUMBER,
    USERNAME      VARCHAR2(100),
    LOGIN_STATUS  VARCHAR2(20) NOT NULL,
    IP_ADDRESS    VARCHAR2(50),
    LOGIN_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_LOGIN_HISTORY PRIMARY KEY (LOGIN_ID),
    CONSTRAINT FK_LOGIN_HISTORY_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_LOGIN_STATUS CHECK (LOGIN_STATUS IN ('SUCCESS', 'FAILED'))
);

--------------------------------------------------------------
-- CREATE PASSWORD_HISTORY TABLE
--------------------------------------------------------------
CREATE TABLE PASSWORD_HISTORY (
    HISTORY_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID        NUMBER NOT NULL,
    PASSWORD_HASH  VARCHAR2(255) NOT NULL,
    CHANGED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PASSWORD_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_PASSWORD_HISTORY_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);

--------------------------------------------------------------
-- CREATE ROLES TABLE
--------------------------------------------------------------
CREATE TABLE ROLES (
    ROLE_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROLE_NAME   VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    STATUS      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMP,

    CONSTRAINT PK_ROLES PRIMARY KEY (ROLE_ID),
    CONSTRAINT UK_ROLES_NAME UNIQUE (ROLE_NAME),
    CONSTRAINT CHK_ROLES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

--------------------------------------------------------------
-- CREATE PERMISSIONS TABLE
--------------------------------------------------------------
CREATE TABLE PERMISSIONS (
    PERMISSION_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PERMISSION_CODE VARCHAR2(100) NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_PERMISSIONS PRIMARY KEY (PERMISSION_ID),
    CONSTRAINT UK_PERMISSIONS_CODE UNIQUE (PERMISSION_CODE),
    CONSTRAINT CHK_PERMISSIONS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

--------------------------------------------------------------
-- CREATE USER_ROLES TABLE
--------------------------------------------------------------
CREATE TABLE USER_ROLES (
    USER_ID     NUMBER NOT NULL,
    ROLE_ID     NUMBER NOT NULL,
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES ROLES(ROLE_ID)
);

--------------------------------------------------------------
-- CREATE ROLE_PERMISSIONS TABLE
--------------------------------------------------------------
CREATE TABLE ROLE_PERMISSIONS (
    ROLE_ID       NUMBER NOT NULL,
    PERMISSION_ID NUMBER NOT NULL,
    ASSIGNED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ROLE_PERMISSIONS PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES ROLES(ROLE_ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_PERMISSION FOREIGN KEY (PERMISSION_ID)
        REFERENCES PERMISSIONS(PERMISSION_ID)
);

