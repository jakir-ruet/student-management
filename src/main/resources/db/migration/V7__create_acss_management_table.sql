-- ACSS Management Tables
-- Academic Year -> Class -> Section -> Shift
-- Oracle Database 23ai
------------------------------------------------------------

------------------------------------------------------------
-- 1. ACADEMIC_YEARS
------------------------------------------------------------
CREATE TABLE ACADEMIC_YEARS (
    ACADEMIC_YEAR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    YEAR_NAME        VARCHAR2(30) NOT NULL,
    START_DATE       DATE NOT NULL,
    END_DATE         DATE NOT NULL,
    IS_CURRENT       CHAR(1) DEFAULT 'N' NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP,

    CONSTRAINT PK_ACADEMIC_YEARS PRIMARY KEY (ACADEMIC_YEAR_ID),
    CONSTRAINT UK_ACADEMIC_YEARS_NAME UNIQUE (YEAR_NAME),
    CONSTRAINT CHK_ACADEMIC_YEARS_CURRENT CHECK (IS_CURRENT IN ('Y', 'N')),
    CONSTRAINT CHK_ACADEMIC_YEARS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CHK_ACADEMIC_YEARS_DATES CHECK (END_DATE > START_DATE)
);

------------------------------------------------------------
-- 2. CLASSES
-- Master class list: Class One, Class Two, etc.
------------------------------------------------------------
CREATE TABLE CLASSES (
    CLASS_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CLASS_NAME    VARCHAR2(100) NOT NULL,
    CLASS_CODE    VARCHAR2(30) NOT NULL,
    DISPLAY_ORDER NUMBER NOT NULL,
    STATUS        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP,

    CONSTRAINT PK_CLASSES PRIMARY KEY (CLASS_ID),
    CONSTRAINT UK_CLASSES_NAME UNIQUE (CLASS_NAME),
    CONSTRAINT UK_CLASSES_CODE UNIQUE (CLASS_CODE),
    CONSTRAINT UK_CLASSES_DISPLAY_ORDER UNIQUE (DISPLAY_ORDER),
    CONSTRAINT CHK_CLASSES_DISPLAY_ORDER CHECK (DISPLAY_ORDER > 0),
    CONSTRAINT CHK_CLASSES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------------------------
-- 3. ACADEMIC_YEAR_CLASSES
-- Which classes are opened for an academic year
-- Example: 2026-2027 -> Class One
------------------------------------------------------------
CREATE TABLE ACADEMIC_YEAR_CLASSES (
    ACADEMIC_YEAR_CLASS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ACADEMIC_YEAR_ID       NUMBER NOT NULL,
    CLASS_ID               NUMBER NOT NULL,
    STATUS                 VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP,

    CONSTRAINT PK_ACADEMIC_YEAR_CLASSES PRIMARY KEY (ACADEMIC_YEAR_CLASS_ID),

    CONSTRAINT FK_AYC_ACADEMIC_YEAR
        FOREIGN KEY (ACADEMIC_YEAR_ID)
        REFERENCES ACADEMIC_YEARS (ACADEMIC_YEAR_ID),

    CONSTRAINT FK_AYC_CLASS
        FOREIGN KEY (CLASS_ID)
        REFERENCES CLASSES (CLASS_ID),

    CONSTRAINT UK_AYC_YEAR_CLASS UNIQUE (ACADEMIC_YEAR_ID, CLASS_ID),
    CONSTRAINT CHK_AYC_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------------------------
-- 4. SECTIONS
-- Sections under opened academic-year class
-- Example: 2026-2027 -> Class One -> Section A
------------------------------------------------------------
CREATE TABLE SECTIONS (
    SECTION_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ACADEMIC_YEAR_CLASS_ID NUMBER NOT NULL,
    SECTION_NAME           VARCHAR2(50) NOT NULL,
    SECTION_CODE           VARCHAR2(30) NOT NULL,
    CAPACITY               NUMBER,
    DISPLAY_ORDER          NUMBER NOT NULL,
    STATUS                 VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP,

    CONSTRAINT PK_SECTIONS PRIMARY KEY (SECTION_ID),

    CONSTRAINT FK_SECTIONS_AYC
        FOREIGN KEY (ACADEMIC_YEAR_CLASS_ID)
        REFERENCES ACADEMIC_YEAR_CLASSES (ACADEMIC_YEAR_CLASS_ID),

    CONSTRAINT UK_SECTIONS_AYC_NAME UNIQUE (ACADEMIC_YEAR_CLASS_ID, SECTION_NAME),
    CONSTRAINT UK_SECTIONS_AYC_CODE UNIQUE (ACADEMIC_YEAR_CLASS_ID, SECTION_CODE),
    CONSTRAINT UK_SECTIONS_AYC_ORDER UNIQUE (ACADEMIC_YEAR_CLASS_ID, DISPLAY_ORDER),

    CONSTRAINT CHK_SECTIONS_CAPACITY CHECK (CAPACITY IS NULL OR CAPACITY > 0),
    CONSTRAINT CHK_SECTIONS_DISPLAY_ORDER CHECK (DISPLAY_ORDER > 0),
    CONSTRAINT CHK_SECTIONS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------------------------
-- 5. SHIFTS
-- Master shift list: Morning, Day, Evening
------------------------------------------------------------
CREATE TABLE SHIFTS (
    SHIFT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SHIFT_NAME    VARCHAR2(50) NOT NULL,
    SHIFT_CODE    VARCHAR2(30) NOT NULL,
    START_TIME    VARCHAR2(5) NOT NULL,
    END_TIME      VARCHAR2(5) NOT NULL,
    DISPLAY_ORDER NUMBER NOT NULL,
    STATUS        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP,

    CONSTRAINT PK_SHIFTS PRIMARY KEY (SHIFT_ID),
    CONSTRAINT UK_SHIFTS_NAME UNIQUE (SHIFT_NAME),
    CONSTRAINT UK_SHIFTS_CODE UNIQUE (SHIFT_CODE),
    CONSTRAINT UK_SHIFTS_DISPLAY_ORDER UNIQUE (DISPLAY_ORDER),

    CONSTRAINT CHK_SHIFTS_START_TIME
        CHECK (REGEXP_LIKE(START_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),

    CONSTRAINT CHK_SHIFTS_END_TIME
        CHECK (REGEXP_LIKE(END_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),

    CONSTRAINT CHK_SHIFTS_DISPLAY_ORDER CHECK (DISPLAY_ORDER > 0),
    CONSTRAINT CHK_SHIFTS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------------------------
-- 6. SECTION_SHIFTS
-- Shift assignment under section
-- Example: Section A -> Morning
------------------------------------------------------------
CREATE TABLE SECTION_SHIFTS (
    SECTION_SHIFT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SECTION_ID       NUMBER NOT NULL,
    SHIFT_ID         NUMBER NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP,

    CONSTRAINT PK_SECTION_SHIFTS PRIMARY KEY (SECTION_SHIFT_ID),

    CONSTRAINT FK_SECTION_SHIFTS_SECTION
        FOREIGN KEY (SECTION_ID)
        REFERENCES SECTIONS (SECTION_ID),

    CONSTRAINT FK_SECTION_SHIFTS_SHIFT
        FOREIGN KEY (SHIFT_ID)
        REFERENCES SHIFTS (SHIFT_ID),

    CONSTRAINT UK_SECTION_SHIFTS_SECTION_SHIFT UNIQUE (SECTION_ID, SHIFT_ID),
    CONSTRAINT CHK_SECTION_SHIFTS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------------------------
-- 7. INDEXES
------------------------------------------------------------
CREATE INDEX IDX_AYC_ACADEMIC_YEAR_ID
ON ACADEMIC_YEAR_CLASSES (ACADEMIC_YEAR_ID);

CREATE INDEX IDX_AYC_CLASS_ID
ON ACADEMIC_YEAR_CLASSES (CLASS_ID);

CREATE INDEX IDX_SECTIONS_AYC_ID
ON SECTIONS (ACADEMIC_YEAR_CLASS_ID);

CREATE INDEX IDX_SECTION_SHIFTS_SECTION_ID
ON SECTION_SHIFTS (SECTION_ID);

CREATE INDEX IDX_SECTION_SHIFTS_SHIFT_ID
ON SECTION_SHIFTS (SHIFT_ID);

