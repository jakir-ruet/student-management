    SEC.SECTION_ID,
    SH.SHIFT_ID,
    'ACTIVE'
FROM SECTIONS SEC
JOIN ACADEMIC_YEAR_CLASSES AYC
    ON AYC.ACADEMIC_YEAR_CLASS_ID = SEC.ACADEMIC_YEAR_CLASS_ID
