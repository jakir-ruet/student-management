                SEC.SECTION_ID,
                SEC.ACADEMIC_YEAR_CLASS_ID,
                AYC.ACADEMIC_YEAR_ID,
                AY.YEAR_NAME,
                AYC.CLASS_ID,
                C.CLASS_NAME,
                C.CLASS_CODE,
                SEC.SECTION_NAME,
                SEC.SECTION_CODE,
                SEC.CAPACITY,
                SEC.DISPLAY_ORDER,
                SEC.STATUS,
                SEC.CREATED_AT,
                SEC.UPDATED_AT
