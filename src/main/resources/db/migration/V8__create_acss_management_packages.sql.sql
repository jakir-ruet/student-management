    PROCEDURE ADD_SHIFT(
        P_SHIFT_NAME    IN SHIFTS.SHIFT_NAME%TYPE,
        P_SHIFT_CODE    IN SHIFTS.SHIFT_CODE%TYPE,
        P_START_TIME    IN SHIFTS.START_TIME%TYPE,
        P_END_TIME      IN SHIFTS.END_TIME%TYPE,
        P_DISPLAY_ORDER IN SHIFTS.DISPLAY_ORDER%TYPE,
        P_STATUS        IN SHIFTS.STATUS%TYPE,
        P_SHIFT_ID      OUT SHIFTS.SHIFT_ID%TYPE
    ) AS
    BEGIN
        INSERT INTO SHIFTS (
            SHIFT_NAME, SHIFT_CODE, START_TIME, END_TIME, DISPLAY_ORDER, STATUS
        ) VALUES (
            P_SHIFT_NAME, P_SHIFT_CODE, P_START_TIME, P_END_TIME, P_DISPLAY_ORDER, P_STATUS
        )
        RETURNING SHIFT_ID INTO P_SHIFT_ID;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20401, 'SHIFT ALREADY EXISTS.');
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20402, 'ERROR CREATING SHIFT: ' || SQLERRM);
    END ADD_SHIFT;


    PROCEDURE UPDATE_SHIFT(
        P_SHIFT_ID      IN SHIFTS.SHIFT_ID%TYPE,
        P_SHIFT_NAME    IN SHIFTS.SHIFT_NAME%TYPE,
        P_SHIFT_CODE    IN SHIFTS.SHIFT_CODE%TYPE,
        P_START_TIME    IN SHIFTS.START_TIME%TYPE,
        P_END_TIME      IN SHIFTS.END_TIME%TYPE,
        P_DISPLAY_ORDER IN SHIFTS.DISPLAY_ORDER%TYPE,
        P_STATUS        IN SHIFTS.STATUS%TYPE
    ) AS
    BEGIN
        UPDATE SHIFTS
        SET SHIFT_NAME    = P_SHIFT_NAME,
            SHIFT_CODE    = P_SHIFT_CODE,
            START_TIME    = P_START_TIME,
            END_TIME      = P_END_TIME,
            DISPLAY_ORDER = P_DISPLAY_ORDER,
            STATUS        = P_STATUS,
            UPDATED_AT    = SYSTIMESTAMP
        WHERE SHIFT_ID = P_SHIFT_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20403, 'SHIFT NOT FOUND.');
        END IF;

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20401, 'SHIFT ALREADY EXISTS.');
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20404, 'ERROR UPDATING SHIFT: ' || SQLERRM);
    END UPDATE_SHIFT;


