                SEC.DISPLAY_ORDER,
                SEC.STATUS,
                SEC.CREATED_AT,
                SEC.UPDATED_AT
            FROM SECTIONS SEC
            JOIN ACADEMIC_YEAR_CLASSES AYC ON AYC.ACADEMIC_YEAR_CLASS_ID = SEC.ACADEMIC_YEAR_CLASS_ID
            JOIN ACADEMIC_YEARS AY ON AY.ACADEMIC_YEAR_ID = AYC.ACADEMIC_YEAR_ID
            JOIN CLASSES C ON C.CLASS_ID = AYC.CLASS_ID
            WHERE SEC.SECTION_ID = P_SECTION_ID;
    END GET_SECTION_BY_ID;


