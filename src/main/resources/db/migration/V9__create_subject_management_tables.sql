-- Subject Management Tables
--------------------------------------------------------

--------------------------------------------------------
-- 1. SUBJECTS
-- Master subject catalog
--------------------------------------------------------
CREATE TABLE SUBJECTS (
    SUBJECT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SUBJECT_NAME    VARCHAR2(100) NOT NULL,
    SUBJECT_CODE    VARCHAR2(30)  NOT NULL,
    SUBJECT_TYPE    VARCHAR2(20)  DEFAULT 'CORE' NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    DISPLAY_ORDER   NUMBER(5),
    STATUS          VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_SUBJECTS PRIMARY KEY (SUBJECT_ID),
    CONSTRAINT UK_SUBJECTS_CODE UNIQUE (SUBJECT_CODE),

    CONSTRAINT CHK_SUBJECTS_TYPE CHECK (
        SUBJECT_TYPE IN ('CORE', 'ELECTIVE', 'OPTIONAL', 'EXTRA')
    ),

    CONSTRAINT CHK_SUBJECTS_STATUS CHECK (
        STATUS IN ('ACTIVE', 'INACTIVE')
    ),

    CONSTRAINT CHK_SUBJECTS_DISPLAY_ORDER CHECK (
        DISPLAY_ORDER IS NULL OR DISPLAY_ORDER > 0
    )
);

--------------------------------------------------------
-- 2. CLASS_SUBJECTS
-- Assign subjects to academic year class
-- Example: Class 6 - 2026 has Bangla, English, Math
--------------------------------------------------------
CREATE TABLE CLASS_SUBJECTS (
    CLASS_SUBJECT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ACADEMIC_YEAR_CLASS_ID  NUMBER NOT NULL,
    SUBJECT_ID              NUMBER NOT NULL,
    IS_MANDATORY            CHAR(1) DEFAULT 'Y' NOT NULL,
    FULL_MARKS              NUMBER(5,2),
    PASS_MARKS              NUMBER(5,2),
    DISPLAY_ORDER           NUMBER(5),
    STATUS                  VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP,

    CONSTRAINT PK_CLASS_SUBJECTS PRIMARY KEY (CLASS_SUBJECT_ID),

    CONSTRAINT FK_CLASS_SUBJECTS_AYC
        FOREIGN KEY (ACADEMIC_YEAR_CLASS_ID)
        REFERENCES ACADEMIC_YEAR_CLASSES (ACADEMIC_YEAR_CLASS_ID),

    CONSTRAINT FK_CLASS_SUBJECTS_SUBJECT
        FOREIGN KEY (SUBJECT_ID)
        REFERENCES SUBJECTS (SUBJECT_ID),

    CONSTRAINT UK_CLASS_SUBJECTS UNIQUE (
        ACADEMIC_YEAR_CLASS_ID,
        SUBJECT_ID
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_MANDATORY CHECK (
        IS_MANDATORY IN ('Y', 'N')
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_STATUS CHECK (
        STATUS IN ('ACTIVE', 'INACTIVE')
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_MARKS CHECK (
        FULL_MARKS IS NULL
        OR PASS_MARKS IS NULL
        OR FULL_MARKS >= PASS_MARKS
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_FULL_MARKS CHECK (
        FULL_MARKS IS NULL OR FULL_MARKS > 0
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_PASS_MARKS CHECK (
        PASS_MARKS IS NULL OR PASS_MARKS >= 0
    ),

    CONSTRAINT CHK_CLASS_SUBJECTS_DISPLAY_ORDER CHECK (
        DISPLAY_ORDER IS NULL OR DISPLAY_ORDER > 0
    )
);

--------------------------------------------------------
-- 3. TEACHER_SUBJECT_ASSIGNMENTS
-- Assign teacher to class subject with section and shift context
-- Example: Teacher teaches Math for Class 6, Section A, Morning
--------------------------------------------------------
CREATE TABLE TEACHER_SUBJECT_ASSIGNMENTS (
    TEACHER_SUBJECT_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CLASS_SUBJECT_ID              NUMBER NOT NULL,
    SECTION_SHIFT_ID              NUMBER NOT NULL,
    TEACHER_ID                    NUMBER NOT NULL,
    ASSIGNMENT_TYPE               VARCHAR2(20) DEFAULT 'PRIMARY' NOT NULL,
    STATUS                        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT                    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                    TIMESTAMP,

    CONSTRAINT PK_TEACHER_SUBJECT_ASSIGNMENTS
        PRIMARY KEY (TEACHER_SUBJECT_ASSIGNMENT_ID),

    CONSTRAINT FK_TSA_CLASS_SUBJECT
        FOREIGN KEY (CLASS_SUBJECT_ID)
        REFERENCES CLASS_SUBJECTS (CLASS_SUBJECT_ID),

    CONSTRAINT FK_TSA_SECTION_SHIFT
        FOREIGN KEY (SECTION_SHIFT_ID)
        REFERENCES SECTION_SHIFTS (SECTION_SHIFT_ID),

    CONSTRAINT FK_TSA_TEACHER
        FOREIGN KEY (TEACHER_ID)
        REFERENCES TEACHERS (TEACHER_ID),

    CONSTRAINT UK_TSA_CLASS_SECTION_TEACHER UNIQUE (
        CLASS_SUBJECT_ID,
        SECTION_SHIFT_ID,
        TEACHER_ID
    ),

    CONSTRAINT CHK_TSA_ASSIGNMENT_TYPE CHECK (
        ASSIGNMENT_TYPE IN ('PRIMARY', 'ASSISTANT', 'SUBSTITUTE')
    ),

    CONSTRAINT CHK_TSA_STATUS CHECK (
        STATUS IN ('ACTIVE', 'INACTIVE')
    )
);

--------------------------------------------------------
-- Indexes
--------------------------------------------------------

CREATE INDEX IDX_CLASS_SUBJECTS_AYC
ON CLASS_SUBJECTS (ACADEMIC_YEAR_CLASS_ID);

CREATE INDEX IDX_CLASS_SUBJECTS_SUBJECT
ON CLASS_SUBJECTS (SUBJECT_ID);

CREATE INDEX IDX_TSA_CLASS_SUBJECT
ON TEACHER_SUBJECT_ASSIGNMENTS (CLASS_SUBJECT_ID);

CREATE INDEX IDX_TSA_SECTION_SHIFT
ON TEACHER_SUBJECT_ASSIGNMENTS (SECTION_SHIFT_ID);

CREATE INDEX IDX_TSA_TEACHER
ON TEACHER_SUBJECT_ASSIGNMENTS (TEACHER_ID);
