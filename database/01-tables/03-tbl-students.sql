---------------------------------------------------------------
-- CREATE STUDENTS TABLE
---------------------------------------------------------------
CREATE TABLE STUDENTS (
    STUDENT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_CODE    VARCHAR2(50) NOT NULL,
    FIRST_NAME      VARCHAR2(100) NOT NULL,
    LAST_NAME       VARCHAR2(100),
    EMAIL           VARCHAR2(150) NOT NULL,
    PHONE           VARCHAR2(30) NOT NULL,
    GENDER          VARCHAR2(20) NOT NULL,
    DATE_OF_BIRTH   DATE NOT NULL,
    ADMISSION_DATE  DATE DEFAULT SYSDATE NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_STUDENTS PRIMARY KEY (STUDENT_ID),
    CONSTRAINT UK_STUDENTS_CODE UNIQUE (STUDENT_CODE),
    CONSTRAINT UK_STUDENTS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_STUDENTS_PHONE UNIQUE (PHONE),
    CONSTRAINT CHK_STUDENTS_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT CHK_STUDENTS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'GRADUATED', 'SUSPENDED'))
);

---------------------------------------------------------------
-- CREATE STUDENT_ADDRESSES TABLE
---------------------------------------------------------------
CREATE TABLE STUDENT_ADDRESSES (
    ADDRESS_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID      NUMBER NOT NULL,
    ADDRESS_TYPE    VARCHAR2(20) DEFAULT 'PRESENT' NOT NULL,
    ADDRESS_LINE    VARCHAR2(500),
    CITY            VARCHAR2(100),
    DISTRICT        VARCHAR2(100),
    POSTAL_CODE     VARCHAR2(20),
    COUNTRY         VARCHAR2(100) DEFAULT 'Bangladesh',
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_STUDENT_ADDRESSES PRIMARY KEY (ADDRESS_ID),
    CONSTRAINT FK_STUDENT_ADDR_STUDENT
       FOREIGN KEY (STUDENT_ID)
           REFERENCES STUDENTS(STUDENT_ID),
    CONSTRAINT CHK_STUDENT_ADDR_TYPE CHECK (ADDRESS_TYPE IN ('PRESENT', 'PERMANENT'))
);

---------------------------------------------------------------
-- CREATE STUDENT_GUARDIANS TABLE
---------------------------------------------------------------
CREATE TABLE STUDENT_GUARDIANS (
    GUARDIAN_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID      NUMBER NOT NULL,
    GUARDIAN_NAME   VARCHAR2(150) NOT NULL,
    RELATIONSHIP    VARCHAR2(50) NOT NULL,
    PHONE           VARCHAR2(30) NOT NULL,
    EMAIL           VARCHAR2(150),
    OCCUPATION      VARCHAR2(200),
    IS_PRIMARY      CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_STUDENT_GUARDIANS PRIMARY KEY (GUARDIAN_ID),
    CONSTRAINT FK_GUARDIAN_STUDENT
       FOREIGN KEY (STUDENT_ID)
           REFERENCES STUDENTS(STUDENT_ID),
    CONSTRAINT CHK_GUARDIAN_PRIMARY CHECK (IS_PRIMARY IN ('Y', 'N'))
);