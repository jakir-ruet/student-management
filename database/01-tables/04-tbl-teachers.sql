---------------------------------------------------------------
-- CREATE TEACHERS TABLE
---------------------------------------------------------------
CREATE TABLE TEACHERS (
    TEACHER_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TEACHER_CODE    VARCHAR2(50) NOT NULL,
    FIRST_NAME      VARCHAR2(100) NOT NULL,
    LAST_NAME       VARCHAR2(100),
    EMAIL           VARCHAR2(150) NOT NULL,
    PHONE           VARCHAR2(30) NOT NULL,
    GENDER          VARCHAR2(20) NOT NULL,
    DATE_OF_BIRTH   DATE NOT NULL,
    JOINING_DATE    DATE DEFAULT SYSDATE NOT NULL,
    DESIGNATION     VARCHAR2(100) NOT NULL,
    QUALIFICATION   VARCHAR2(200),
    DEPARTMENT      VARCHAR2(100),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_TEACHERS PRIMARY KEY (TEACHER_ID),
    CONSTRAINT UK_TEACHERS_CODE UNIQUE (TEACHER_CODE),
    CONSTRAINT UK_TEACHERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_TEACHERS_PHONE UNIQUE (PHONE),
    CONSTRAINT CHK_TEACHERS_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT CHK_TEACHERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'RESIGNED', 'SUSPENDED'))
);

---------------------------------------------------------------
-- CREATE TEACHER_ADDRESSES TABLE
---------------------------------------------------------------
CREATE TABLE TEACHER_ADDRESSES (
    ADDRESS_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TEACHER_ID      NUMBER NOT NULL,
    ADDRESS_TYPE    VARCHAR2(20) DEFAULT 'PRESENT' NOT NULL,
    ADDRESS_LINE    VARCHAR2(500),
    CITY            VARCHAR2(100),
    DISTRICT        VARCHAR2(100),
    POSTAL_CODE     VARCHAR2(20),
    COUNTRY         VARCHAR2(100) DEFAULT 'Bangladesh',
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_TEACHER_ADDRESSES PRIMARY KEY (ADDRESS_ID),
    CONSTRAINT FK_TEACHER_ADDR_TEACHER
        FOREIGN KEY (TEACHER_ID)
		  REFERENCES TEACHERS(TEACHER_ID),
    CONSTRAINT CHK_TEACHER_ADDR_TYPE CHECK (ADDRESS_TYPE IN ('PRESENT', 'PERMANENT')),
    CONSTRAINT UK_TEACHER_ADDRESS_TYPE UNIQUE (TEACHER_ID, ADDRESS_TYPE)
);

---------------------------------------------------------------
-- CREATE TEACHER_CONTACTS TABLE
---------------------------------------------------------------
CREATE TABLE TEACHER_CONTACTS (
    CONTACT_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TEACHER_ID      NUMBER NOT NULL,
    CONTACT_NAME    VARCHAR2(150) NOT NULL,
    RELATIONSHIP    VARCHAR2(50) NOT NULL,
    PHONE           VARCHAR2(30) NOT NULL,
    EMAIL           VARCHAR2(150),
    IS_PRIMARY      CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP,

    CONSTRAINT PK_TEACHER_CONTACTS PRIMARY KEY (CONTACT_ID),
    CONSTRAINT FK_TEACHER_CONTACT_TEACHER
        FOREIGN KEY (TEACHER_ID)
		  REFERENCES TEACHERS(TEACHER_ID),
    CONSTRAINT CHK_TEACHER_CONTACT_PRIMARY CHECK (IS_PRIMARY IN ('Y', 'N'))
);
