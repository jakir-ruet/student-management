CREATE TABLE USERS (
    USER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USERNAME       VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(150) NOT NULL,
    PASSWORD_HASH  VARCHAR2(255) NOT NULL,
    FULL_NAME      VARCHAR2(150) NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    FAILED_LOGIN   NUMBER DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CHK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE TABLE LOGIN_HISTORY (
    LOGIN_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID       NUMBER,
    USERNAME      VARCHAR2(100),
    LOGIN_STATUS  VARCHAR2(20) NOT NULL,
    IP_ADDRESS    VARCHAR2(50),
    LOGIN_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_LOGIN_HISTORY PRIMARY KEY (LOGIN_ID),
    CONSTRAINT FK_LOGIN_HISTORY_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_LOGIN_STATUS
        CHECK (LOGIN_STATUS IN ('SUCCESS', 'FAILED'))
);

CREATE TABLE PASSWORD_HISTORY (
    HISTORY_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID        NUMBER NOT NULL,
    PASSWORD_HASH  VARCHAR2(255) NOT NULL,
    CHANGED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PASSWORD_HISTORY PRIMARY KEY (HISTORY_ID),
    CONSTRAINT FK_PASSWORD_HISTORY_USER
        FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

